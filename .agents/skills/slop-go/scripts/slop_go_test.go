func TestGoBroaderVerbosityPatterns(t *testing.T) {
	dir := t.TempDir()
	putGoFixture(t, dir, "sample.go", `package demo
func expensive() bool { return true }
func f(a, b int, text string) (int, string) {
 if expensive() { return a + 0, text + "" }
 if a > b { return a, text }
 return b, text
}
func pick(a, b int) int {
 if a > b { return a }
 return b
}
func boolValue(x bool) bool {
 return x && true
}
func boolGuard() bool {
 if expensive() { return true }
 return false
}
func threeLines() {
 if true {
  println("same")
 }
 println("again")
}
func otherThreeLines() {
 if true {
  println("same")
 }
 println("again")
}
`)
	r, err := analyzeGoProject(dir, ".", false)
	if err != nil {
		t.Fatal(err)
	}
	for _, rule := range []string{"numeric-identity", "empty-string-concat", "boolean-identity", "manual-min-max-return", "boolean-return-guard"} {
		if !hasGoRule(r, rule) {
			t.Errorf("missing broader rule %q", rule)
		}
	}
	if r.CloneLines == 0 {
		t.Fatal("expected three-SLOC duplicated block")
	}
}

