func TestGoRulesAdaptConditionalAndLoopPatterns(t *testing.T) {
	dir := t.TempDir()
	putGoFixture(t, dir, "sample.go", `package demo
func f(v bool) bool {
 if v { if !v { println("impossible") } }
 if v { return true }
 return false
}
func loop() {
 for i := 0; i < 3; i++ {
  if i == 1 { continue }
  if i == 2 { continue }
  println(i)
  continue
 }
}
`)
	r, err := analyzeGoProject(dir, ".", false)
	if err != nil {
		t.Fatal(err)
	}
	for _, rule := range []string{"nested-if-no-else", "boolean-return-guard", "repeated-if-continue", "redundant-continue"} {
		if !hasGoRule(r, rule) {
			t.Errorf("missing adapted %s: %+v", rule, r.Findings)
		}
	}
}
